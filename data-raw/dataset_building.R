# ==============================================================================
# SCRIPT 2: DIGITAL SIGNAL PROCESSING & FEATURE EXTRACTION
# ==============================================================================
# Package: AvianEchoR
# Purpose: Parses raw MP3/WAV recordings, slices them mathematically based on
#          vocalization spikes, and maps them into a 15-Dimensional feature space.
#
# Pipeline:
#   1. Scans the downloaded acoustic folder.
#   2. Balances the dataset (capping files per species) and splits 80/20.
#   3. Passes files to AvianEchoR::extract_clean_chunks() for VAD slicing.
#   4. Passes chunks to AvianEchoR::extract_audio_features() for DSP math.
#   5. Saves memory-safe checkpoints to prevent RAM overflow.
#
# Execution: Run this script from the terminal using `Rscript feature_extraction.R`
# ==============================================================================

library(tuneR)
library(dplyr)
library(seewave)
library(AvianEchoR)

# ==============================================================================
# 1. SETUP DATASET & METADATA
# ==============================================================================
# Point to the generalized folder created by Script 1
audio_dir <- "AvianEcho_Audio_Files"

if (!dir.exists(audio_dir)) {
  stop("❌ Directory not found. Please run Script 1 (downloading.R) first.")
}

# Matches both mp3 and wav files, ignoring case
files <- list.files(audio_dir, pattern = "\\.(mp3|wav|MP3|WAV)$", recursive = TRUE, full.names = TRUE)

if(length(files) == 0) stop("❌ No MP3 or WAV files found in the target directory.")

cat(sprintf("Found %d audio files. Building metadata...\n", length(files)))

# Create metadata based on the folder names generated by the downloader
metadata <- data.frame(
  path = files,
  species = basename(dirname(files))
)

# Find species that successfully downloaded at least 15 files
good_species <- metadata %>% count(species) %>% filter(n >= 15) %>% pull(species)

set.seed(42)

# Step 1: Cap EVERY species at exactly 15 files for perfect initial balance
meta_subset <- metadata %>%
  filter(species %in% good_species) %>%
  group_by(species) %>%
  slice_sample(n = 15)

# Step 2: 80/20 Split (12 Train / 3 Test)
train <- meta_subset %>% group_by(species) %>% slice_sample(n = 12)
test <- anti_join(meta_subset, train, by = c("path", "species"))

# Verify the math!
cat("\n==================================================\n")
cat(sprintf("TRAINING FILES: %d\nTESTING FILES:  %d\n", nrow(train), nrow(test)))
cat("==================================================\n")


# ==============================================================================
# 2. MEMORY-SAFE BATCH PROCESSOR
# ==============================================================================
process_in_batches <- function(df, dataset_name, batch_size = 50) {
  num_batches <- ceiling(nrow(df) / batch_size)
  all_batches <- list()

  for (b in 1:num_batches) {
    checkpoint_name <- sprintf("data/%s_checkpoint_batch_%d.rds", dataset_name, b)

    # SMART RESUME: Skip batches that are already finished!
    if (file.exists(checkpoint_name)) {
      cat(sprintf("\n⏭️ Skipping %s Batch %d (Checkpoint found)...\n", dataset_name, b))
      all_batches[[b]] <- readRDS(checkpoint_name)
      next
    }

    cat(sprintf("\nProcessing %s Batch %d of %d...\n", dataset_name, b, num_batches))

    start_idx <- ((b - 1) * batch_size) + 1
    end_idx <- min(b * batch_size, nrow(df))
    batch_results <- list()

    # Loop through the exact files for this batch
    for (i in start_idx:end_idx) {

      current_file <- basename(df$path[i])

      # Print file name first; extract_clean_chunks will append its duration output
      cat(sprintf("  -> [%d/%d] Reading: %s ... ", i, nrow(df), current_file))

      # 1. Use the PACKAGE function to get clean bird chirps
      wave_chunks <- AvianEchoR::extract_clean_chunks(df$path[i], max_duration_sec = 180)

      # 2. If the algorithm found valid chirps, loop through each one
      if (length(wave_chunks) > 0) {
        for (c in seq_along(wave_chunks)) {

          # Extract the features for THIS specific, clean chunk
          features <- tryCatch({
            AvianEchoR::extract_audio_features(wave_chunks[[c]], verbose = FALSE)
          }, error = function(e) NULL)

          if (!is.null(features)) {
            features$species <- df$species[i]
            features$original_file <- current_file
            features$chunk_id <- c

            batch_results[[length(batch_results) + 1]] <- features
          }
        }
      }
    }

    batch_df <- do.call(rbind, batch_results)
    all_batches[[b]] <- batch_df

    # Save checkpoint to the data folder
    dir.create("data", showWarnings = FALSE)
    saveRDS(batch_df, checkpoint_name)

    gc() # Force memory garbage collection
  }

  return(do.call(rbind, all_batches))
}

# ==============================================================================
# 3. RUN EXTRACTION
# ==============================================================================
cat("\nStarting extraction. This will utilize the package's DSP engine...\n")

# Process and save Training Data
train_features <- process_in_batches(train, "Train")
saveRDS(train_features, "data-raw/bird_train.rds")

# Process and save Testing Data
test_features <- process_in_batches(test, "Test")
saveRDS(test_features, "data-raw/bird_test.rds")

cat("\n✅ SUCCESS! Custom dataset safely extracted and saved to data/ directory.\n")
